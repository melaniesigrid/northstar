import { describe, expect, it } from "vitest";
import { findAttributionMarkers } from "../src/attribution.js";

// Fixture lines are assembled from parts so this file does not trip the check it tests.
const TOOL = "Claude";
const trailer = `Co-Authored-By: ${TOOL} <noreply@example.com>`;
const footer = `Generated with ${TOOL} Code`;

function markedLines(...lines: string[]): string[] {
  const added = lines.map((text, index) => ({ file: "README.md", number: index + 1, text }));
  return findAttributionMarkers(added).map((marker) => marker.text);
}

describe("findAttributionMarkers", () => {
  it.each([
    [trailer],
    [footer],
    [`// written by ${"ChatGPT"}`],
    [`<!-- created using an ${"AI"} assistant -->`],
    [`# This module was authored with ${"Copilot"}.`],
  ])("flags %s", (line) => {
    expect(markedLines(line)).toHaveLength(1);
  });

  it("reports where the note is, in any kind of file", () => {
    const added = [{ file: "docs/guide.md", number: 12, text: `  ${footer}  ` }];

    expect(findAttributionMarkers(added)).toEqual([{ file: "docs/guide.md", line: 12, text: footer }]);
  });

  it.each([
    ["Supports Claude Code and Codex as writer or reviewer."],
    ["Co-authored-by: Dana Lee <dana@example.com>"],
    ["The report is generated by the gate runner."],
    ["const cursor = rows.findIndex(isActive);"],
    ["Created by the onboarding team in 2024."],
  ])("does not flag %s", (line) => {
    expect(markedLines(line)).toEqual([]);
  });
});
